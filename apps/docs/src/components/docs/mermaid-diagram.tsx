import { Effect } from "effect";
import { useMemo } from "react";
import { renderMermaid } from "./mermaid";

/**
 * One Mermaid diagram, painted from its source.
 *
 * `render` is synchronous and pure, so the diagram is in the prerendered HTML:
 * a reader gets the drawing before any script runs. A source Pele refuses puts
 * the parser's sentence on the page instead of an empty box, and the source is
 * still printed under it, because a diagram you cannot see is a source you have
 * to fix.
 */
export function MermaidDiagram({
  source,
  caption,
}: {
  readonly source: string;
  readonly caption?: string;
}) {
  const rendered = useMemo(
    () =>
      Effect.runSync(
        Effect.match(renderMermaid(source), {
          onFailure: (error) => ({
            ok: false as const,
            message: error.message,
          }),
          onSuccess: (svg) => ({ ok: true as const, svg }),
        }),
      ),
    [source],
  );

  return (
    <figure className="gx-mermaid">
      {rendered.ok ? (
        <div
          aria-label={caption ?? "Diagram"}
          className="gx-mermaid-svg"
          dangerouslySetInnerHTML={{ __html: rendered.svg }}
          role="img"
          // The markup is generated by a pure function from the same source on
          // both sides, so it is identical: `render` is synchronous and reads
          // no clock, randomness or measurement. React's dev check compares the
          // string byte for byte against the browser's *normalised* parse of
          // the same SVG, which differs by serialisation only (`<rect/>` versus
          // `<rect></rect>`, attribute quoting), and there is nothing to patch.
          suppressHydrationWarning
        />
      ) : (
        <div className="gx-mermaid-error" role="status">
          <p className="gx-mermaid-error-title">
            This diagram could not be read
          </p>
          <p className="gx-mermaid-error-body">{rendered.message}</p>
          <pre className="gx-mermaid-error-source">{source}</pre>
        </div>
      )}
      {caption === undefined ? null : (
        <figcaption className="gx-mermaid-caption">{caption}</figcaption>
      )}
    </figure>
  );
}
