import { readdirSync, readFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { packageCollections } from "./collection-routes";

/**
 * `apps/docs/README.md` is the site's ledger: which pages exist and which
 * module owns which part of the site.
 *
 * It drifted the way a hand-maintained list does — ten shipped pages
 * (`patterns`, `runtime`, `themes`, `license`, the four blocks, …) and two dozen
 * modules had no line at all — so a contributor reading the ledger could not
 * find the page or the file they were about to edit. The guard reads the tree
 * and fails on what the ledger does not name, in the ledger's own format: a
 * line that begins with the path.
 */

const appDir = fileURLToPath(new URL("../../", import.meta.url));
const ledger = readFileSync(join(appDir, "README.md"), "utf8").split("\n");

/** True when a line of the ledger begins with `path`. */
const listed = (path: string): boolean =>
  ledger.some((line) => {
    const entry = line.trimStart();
    return entry.startsWith(path) && /^(?:$|\s)/.test(entry.slice(path.length));
  });

const walk = (
  dir: string,
  keep: (name: string) => boolean,
): ReadonlyArray<string> =>
  readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) return walk(full, keep);
    return keep(entry.name) ? [relative(appDir, full)] : [];
  });

/** Pages are listed relative to `content/docs/`, modules from the app root. */
const pages = walk(join(appDir, "content/docs"), (name) =>
  name.endsWith(".mdx"),
).map((path) => path.slice("content/docs/".length));

const modules = [
  ...walk(join(appDir, "src"), (name) => /\.(?:ts|tsx|css)$/.test(name)),
  ...walk(join(appDir, "plugins"), (name) => name.endsWith(".ts")),
].filter(
  (path) =>
    // Generated by the TanStack Start plugin on every build, never edited.
    path !== "src/routeTree.gen.ts" &&
    // A test helper the sidebar guards import, not site source.
    path !== "src/lib/sidebar-pages.test-util.ts" &&
    !path.includes(".test."),
);

describe("the apps/docs ledger", () => {
  it("names every page the site ships", () => {
    // A floor, so a scan that stopped matching cannot pass.
    expect(pages.length).toBeGreaterThanOrEqual(20);
    expect(pages.filter((page) => !listed(page))).toEqual([]);
  });

  it("names every module the site is built from", () => {
    expect(modules.length).toBeGreaterThanOrEqual(50);
    expect(modules.filter((module) => !listed(module))).toEqual([]);
  });

  it("points at the preview policy it tells a contributor to read", () => {
    expect(ledger.join("\n")).toContain("docs/preview-strategy.md");
    const policy = readFileSync(
      new URL("../../../../docs/preview-strategy.md", import.meta.url),
      "utf8",
    );
    // The file, not just the mention: the policy is the page template.
    expect(policy).toContain("## The strategy");
  });

  it("says the sidebar offers platforms, not a look control it retired", () => {
    // `8c180a9f` removed the Look group, and `/docs/theming` and the preview
    // policy were corrected with it. The site's own ledger still described a
    // **Look** group and a "look picker" no reader can press, so a contributor
    // would look for the control and change the wrong file. The page, not the
    // policy, is the name the ledger has to match.
    const readme = ledger.join("\n");
    const page = readFileSync(
      new URL("../../content/docs/theming.mdx", import.meta.url),
      "utf8",
    );

    expect(page).toContain("### The look parameter");
    expect(readme).toContain("## The platform switch and the look parameter");
    expect(readme).toContain("no look group");
    expect(readme).toContain("?look=luna");
    expect(readme).not.toContain("look picker");
    expect(readme).not.toContain("**Look** offers");
  });

  it("keeps every curated line on the page the site actually serves", () => {
    // A curated page shadows its package page at the same URL, and the site
    // serves one page per URL (the preview policy records the displacement).
    // The Button line still said "the package page keeps the API": that page is
    // not mounted, and the curated page carries its own `## API reference`, so
    // the ledger sent a contributor to a route no reader can reach.
    const curated = ledger.filter((line) =>
      /^\s*components\/[a-z0-9-]+\.mdx/.test(line),
    );
    const button =
      curated.find((line) => line.includes("components/button.mdx")) ?? "";
    const page = readFileSync(
      new URL("../../content/docs/components/button.mdx", import.meta.url),
      "utf8",
    );

    expect(curated.length).toBeGreaterThanOrEqual(30);
    expect(curated.filter((line) => line.includes("package page"))).toEqual([]);
    expect(page).toContain("## API reference");
    expect(button).toContain("API");
  });

  it("describes the search index without a count the collections outgrew", () => {
    // The ledger said search ran "over all four collections" long after the
    // site mounted nine package collections under it: a contributor reading
    // the line believed a workspace, media or data page was not searchable.
    // The wording is count-free now, and the registry is the thing that knows
    // how many floors the index has.
    const search =
      ledger.find((line) => line.includes("src/routes/api/search.ts")) ?? "";

    expect(packageCollections.length).toBeGreaterThan(4);
    expect(search).toContain("every mounted collection");
    expect(search).not.toMatch(/\b(four|three|nine)\b/);
  });
});
