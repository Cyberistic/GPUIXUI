import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { partStates, type PartState } from "./part-states";

/**
 * The source reader and module renderer behind the generated part-state table
 * (plan 623). `node:fs` stays in this module: the component imports the
 * generated data, and only the generator script and its guard import this file.
 *
 * Sync I/O is deliberate at this boundary — the readers are a one-shot build
 * script and a test, not runtime code, the same rule `scripts/api-values.ts`
 * follows. `JSON.stringify` emits source text here; nothing is parsed.
 */

const isSource = (name: string): boolean =>
  /\.(ts|tsx)$/.test(name) &&
  !/\.test\.(ts|tsx)$/.test(name) &&
  !name.startsWith("behaviour/");

/** Every exported state interface under `packages/components/src`, by path. */
export const readPartStates = (root: string): ReadonlyArray<PartState> => {
  const sourceRoot = join(root, "packages/components/src");
  const sources = readdirSync(sourceRoot, {
    recursive: true,
    encoding: "utf8",
  })
    .filter(isSource)
    .toSorted()
    .map((name) => {
      const file = name.replaceAll("\\", "/");
      return {
        path: `packages/components/src/${file}`,
        text: readFileSync(join(sourceRoot, name), "utf8"),
      };
    });
  return partStates(sources);
};

const row = (state: PartState): string => `  {
    name: ${JSON.stringify(state.name)},
    file: ${JSON.stringify(state.file)},
    fields: [${state.fields.map((field) => JSON.stringify(field)).join(", ")}],
  },`;

/** The committed module, with the command that regenerates it. */
export const renderPartStatesModule = (
  states: ReadonlyArray<PartState>,
): string => `// Generated by \`nub run --filter docs part-states\` from
// \`packages/components/src\` (plan 623). Do not edit: the guard fails when this
// file is stale.
import type { PartState } from "./part-states.js";

export const stateTypes: readonly PartState[] = [
${states.map(row).join("\n")}
];
`;
