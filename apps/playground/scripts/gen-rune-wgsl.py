#!/usr/bin/env python3
"""Adapts rune-fx's WGSL to paint_shader. Usage: gen-rune-wgsl.py <rune-fx shaders dir> <out.ts>"""
import json, re, sys

src, out = sys.argv[1:]
common = open(f"{src}/common.wgsl").read()
common = re.sub(r"@group\(\d\) @binding\(\d\) var[^\n]*\n", "", common)
a, b = common.index("struct VOut {"), common.index("fn effective_blend_mode")
common = common[:a] + "struct VOut { id: u32, px: vec2f }\nfn pixel(in: VOut) -> vec2f { return in.px; }\n" + common[b:]
a, b = common.index("// Every effect module defines"), common.index("const TAU")
common = common[:a] + common[b:]
a, b = common.index("fn bd(p: vec2f"), common.index("struct VOut")
common = common[:a] + """fn bd(p: vec2f, scale: f32) -> vec4f { return bd_lin(backdrop_at(p)); }
fn bdb(p: vec2f, scale: f32) -> vec3f {
    var acc = vec3f(0.0);
    for (var k = 0u; k < 48u; k++) {
        let f = (f32(k) + 0.5) / 48.0;
        let a = f32(k) * 2.39996;
        acc += bd(p + vec2f(cos(a), sin(a)) * sqrt(f) * frost_radius(), scale).rgb;
    }
    return acc / 48.0;
}
""" + common[b:]


def fix(s):
    s = re.sub(r"@group\(\d\) @binding\(\d\) var[^\n]*\n", "", s)
    s = s.replace("insts[in.id]", "inst_at()")
    s = s.replace("g.viewport", "frame.viewport").replace("g.dither", "1.0").replace("g.srgb", "1.0")
    s = s.replace("backdrop_encoding.x", "1.0").replace("backdrop_encoding.y", "1.0")
    result, i = "", 0
    while True:
        m = re.search(r"\bdata\[", s[i:])
        if not m:
            result += s[i:]
            break
        start = i + m.start()
        result += s[i:start]
        j, depth = i + m.end(), 1
        while depth:
            depth += {"[": 1, "]": -1}.get(s[j], 0)
            j += 1
        result += "shader_data_at(" + s[i + m.end() : j - 1] + ")"
        i = j
    s = re.sub(r"\bsource\b", "simulation_state", result)
    s = re.sub(r"\bsamp\b", "backdrop_sampler", s)
    s = s.replace("select(c.p, c.q, i.p2.x > 0.5)", "select(c.p + frame.bounds.xy / frame.scale, c.q, i.p2.x > 0.5)")
    return s.replace("fn shade(in: VOut)", "fn rune_shade(in: VOut)")


GLUE = """
fn inst_at() -> Inst {
    var i: Inst;
    i.rect = frame.params[0]; i.shape = frame.params[1]; i.shape.y = frame.scale; i.bounds = vec4f(0.0);
    i.c0 = frame.params[2]; i.c1 = frame.params[3]; i.c2 = frame.params[4];
    i.p0 = frame.params[5]; i.p1 = frame.params[6]; i.p2 = frame.params[7]; i.p3 = frame.params[8];
    i.t = frame.params[9]; i.t.x = frame.time;
    i.aux = frame.params[10]; i.aux2 = frame.params[11]; i.xf = frame.params[12];
    return i;
}
fn frost_radius() -> f32 { return frame.params[13].x; }
fn shade(p: vec2f) -> vec4f {
    var v: VOut; v.id = 0u; v.px = p * frame.scale;
    let c = rune_shade(v) * frame.params[1].z;
    let cover = min(max(c.rgb, vec3f(0.0)), vec3f(c.a));
    let straight = select(vec3f(0.0), cover / c.a, c.a > 1e-6);
    return vec4f(to_srgb(straight) * c.a + to_srgb(max(c.rgb, vec3f(0.0)) - cover), c.a);
}
"""
ts = "// Generated by scripts/gen-rune-wgsl.py from rune-fx (MIT, © Anomaly), crates/rune-fx/src/shaders.\n"
ts += "const COMMON = " + json.dumps(fix(common) + GLUE) + ";\n"
for name in ["glow", "pulse", "electric", "extras", "distort", "fill"]:
    ts += f"export const {name.upper()} = COMMON + " + json.dumps(fix(open(f"{src}/{name}.wgsl").read())) + ";\n"
open(out, "w").write(ts)
