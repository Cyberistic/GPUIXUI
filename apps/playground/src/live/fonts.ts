/**
 * The typeface the `register-font` probe installs, and the geometry that proves
 * the runtime painted it.
 *
 * A font is only provable from its **metrics**: a family the runtime does not
 * know falls back to the system face, so the probe needs a face whose widths no
 * system font produces. `GpuixTestSquare` (from GPUix's own test suite) is that
 * face — every glyph is a filled square whose advance is a whole number of ems,
 * declared at 1000 units per em.
 *
 * Provenance: `references/gpuix/packages/react/src/__tests__/fixtures/gpuix-test-square.ttf`
 * at the pinned upstream revision, generated by the `make-square-font.py`
 * beside it (`pip install fonttools`). The bytes are embedded rather than read
 * from disk so the runner stays one build artefact with no asset-copy step; a
 * unit test decodes them and checks the family the file declares.
 */
import * as Arr from "effect/Array";
import type { FontSource } from "@gpuixui/tokens";

/** One glyph in the face: the character it draws and its advance in ems. */
export interface SquareGlyph {
  readonly char: string;
  readonly em: number;
}

/** Every glyph the face draws, from the generator's own width table. */
export const SQUARE_GLYPHS: ReadonlyArray<SquareGlyph> = [
  { char: "A", em: 1 },
  { char: "B", em: 2 },
  { char: "m", em: 1 },
];

/** The family the font file's name table declares; a theme must name exactly this. */
export const SQUARE_FAMILY = "GpuixTestSquare";

/** A family no runtime knows, so its text must paint the fallback face. */
export const MISSING_FAMILY = "GpuixTestMissing";

/** The pixel size the probe paints at, so one em is this many pixels. */
export const SQUARE_SIZE = 20;

/** The sample word: every glyph the face draws, so its width is every advance. */
export const SQUARE_WORD = Arr.join(
  Arr.map(SQUARE_GLYPHS, (glyph) => glyph.char),
  "",
);

/**
 * The width the face lays `SQUARE_WORD` out at, in pixels.
 *
 * The fallback face cannot match it: four ems of filled squares at 20px is 80,
 * while `"ABm"` in any system UI face at 20px is nearer 35. The probe's
 * tolerance is one pixel because layout rounds to whole pixels.
 */
export const SQUARE_WORD_WIDTH =
  Arr.reduce(SQUARE_GLYPHS, 0, (total, glyph) => total + glyph.em) *
  SQUARE_SIZE;

